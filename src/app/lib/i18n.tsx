const diccionarios: Record<Idioma, Record<Clave, string>> = { en, es };
const LLAVE = 'fintwin:idioma';

function idiomaInicial(): Idioma {
  try {
    const guardado = localStorage.getItem(LLAVE);
    if (guardado === 'en' || guardado === 'es') return guardado;
  } catch {
    /* sin almacenamiento */
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en';
}

interface Ctx {
  idioma: Idioma;
  setIdioma: (i: Idioma) => void;
  t: (clave: Clave, vars?: Record<string, string | number>) => string;
}

const I18n = createContext<Ctx | null>(null);

export function I18nProvider({ children, inicial }: { children: ReactNode; inicial?: Idioma }) {
  const [idioma, setIdiomaState] = useState<Idioma>(inicial ?? idiomaInicial);
  const setIdioma = useCallback((i: Idioma) => {
    setIdiomaState(i);
    try {
      localStorage.setItem(LLAVE, i);
    } catch {
      /* sin almacenamiento */
    }
    document.documentElement.lang = i;
  }, []);
  const t = useCallback(
    (clave: Clave, vars?: Record<string, string | number>) => {
      let s = diccionarios[idioma][clave] ?? en[clave];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [idioma],
  );
  const value = useMemo(() => ({ idioma, setIdioma, t }), [idioma, setIdioma, t]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18n);
  if (!c) throw new Error('useI18n fuera de I18nProvider');
  return c;
}

/** Mensaje en palabras para un código de error del servidor. */
export function useMensajeError() {
  const { t } = useI18n();
  return (e: unknown): string => {
    const err = e as { code?: string; data?: Record<string, unknown> };
    const code = err?.code ?? 'error_interno';
    const clave = `err.${code}` as Clave;
    if (!(clave in en)) return t('err.error_interno');
    return t(clave, {
      min: String(err.data?.esperar_min ?? 15),
      n: String(err.data?.quedan ?? 0),
    });
  };
}

export type { Clave };
